<?php
namespace InkOS\Woo;

defined( 'ABSPATH' ) || exit;

final class Orders {
	const ACTION = 'inkos_woo_send_order';
	const GROUP = 'inkos-woocommerce';

	public static function hooks() {
		add_action( 'woocommerce_checkout_order_processed', static function ( $id, $data, $order ) {
			self::prepare( $order );
		}, 10, 3 );
		add_action( 'woocommerce_store_api_checkout_order_processed', static function ( $order ) {
			try {
				self::prepare( $order );
			} catch ( ApiError $error ) {
				throw new \Automattic\WooCommerce\StoreApi\Exceptions\RouteException( 'inkos_checkout', $error->getMessage(), $error->retryable() ? 503 : 409 );
			}
		} );
		add_action( 'woocommerce_before_pay_action', static function ( $order ) {
			try {
				self::prepare( $order );
			} catch ( ApiError $error ) {
				wc_add_notice( $error->getMessage(), 'error' );
				wp_safe_redirect( $order->get_checkout_payment_url() );
				exit;
			}
		} );
		add_action( 'woocommerce_order_status_changed', static function ( $id, $from, $to ) {
			if ( in_array( $to, array( 'processing', 'completed', 'on-hold' ), true ) ) {
				self::send( $id );
			}
		}, 20, 3 );
		add_action( 'woocommerce_payment_complete', array( __CLASS__, 'send' ) );
		add_action( self::ACTION, array( __CLASS__, 'send' ), 10, 2 );
		add_action( 'woocommerce_admin_order_data_after_order_details', array( __CLASS__, 'panel' ) );
		add_filter( 'woocommerce_order_actions', static function ( $actions, $order ) {
			if ( $order && $order->get_meta( '_inkos_draft' ) && ! $order->get_meta( '_inkos_receipt' ) && current_user_can( 'manage_woocommerce' ) ) {
				$actions['inkos_retry'] = 'Retry InkOS synchronization';
			}
			return $actions;
		}, 10, 2 );
		add_action( 'woocommerce_order_action_inkos_retry', static function ( $order ) {
			// WooCommerce checks its order-action nonce before dispatching this hook.
			if ( current_user_can( 'manage_woocommerce' ) && current_user_can( 'edit_shop_order', $order->get_id() ) ) {
				self::send( $order->get_id(), 0, true );
			}
		} );
		add_action( 'woocommerce_privacy_before_remove_order_personal_data', array( __CLASS__, 'erase_contact' ) );
		add_action( 'woocommerce_delete_order', static function ( $id ) {
			delete_option( self::outbox_name( $id ) );
		} );
	}

	private static function cents( $amount ) {
		return (int) round( (float) $amount * 100 );
	}

	// Freeze buyer-authorized line references and the contact before the gateway runs.
	public static function prepare( $order ) {
		$items = array();
		$total = 0;
		foreach ( $order->get_items() as $line ) {
			$q = $line->get_meta( '_inkos_terms' );
			$product = $line->get_product();
			if ( ! $q && ( ! $product || ! $product->get_meta( '_inkos_configuration' ) ) ) {
				continue;
			}
			Cart::verify( $q, $product, $line->get_quantity(), $line->get_meta( '_inkos_storefront' ) );
			if ( $q['currency'] !== $order->get_currency() || self::cents( $line->get_total() ) !== $q['totalMinor'] || self::cents( $line->get_total_tax() ) ) {
				throw new ApiError( 'total_mismatch', 'The order line total differs from the agreed InkOS price. Review your cart before payment.', 409 );
			}
			$total += $q['totalMinor'];
			$items[] = array( 'quoteId' => $q['quoteId'] );
		}
		if ( ! $items ) {
			if ( $order->get_meta( '_inkos_draft' ) ) {
				$order->delete_meta_data( '_inkos_draft' );
				$order->delete_meta_data( '_inkos_state' );
				$order->save();
			}
			return;
		}
		if ( count( $items ) !== count( $order->get_items() ) || count( $items ) > 50 || count( array_unique( array_column( $items, 'quoteId' ) ) ) !== count( $items )
			|| $total !== self::cents( $order->get_total() ) || $order->get_items( 'fee' ) || self::cents( $order->get_shipping_total() ) || self::cents( $order->get_discount_total() ) || self::cents( $order->get_total_tax() ) ) {
			throw new ApiError( 'unsupported_total', 'Check out print items separately with the exact InkOS total. Remove coupons and choose a free delivery or pickup method. Contact the shop if taxes or fees differ.', 409 );
		}
		if ( 'yes' === $order->get_meta( '_anonymized' ) ) {
			throw new ApiError( 'customer_erased', 'This order was anonymized and cannot be submitted for printing.', 409 );
		}
		$name = trim( $order->get_billing_first_name() . ' ' . $order->get_billing_last_name() );
		$email = $order->get_billing_email();
		if ( '' === $name || ! is_email( $email ) ) {
			throw new ApiError( 'customer_required', 'Enter a billing name and email for this print order.', 400 );
		}
		// The order key is generated by WooCommerce. Hash it so the checkout access secret stays on the store.
		$external = 'wc-' . $order->get_id() . '-' . substr( hash( 'sha256', $order->get_order_key() ), 0, 24 );
		$draft = array(
			'storefront' => Api::storefront(), 'currency' => $order->get_currency(), 'totalMinor' => $total,
			'body' => array( 'externalOrderId' => $external, 'customer' => array( 'name' => $name, 'email' => $email ), 'items' => $items ),
		);
		$order->update_meta_data( '_inkos_draft', $draft );
		$order->update_meta_data( '_inkos_state', 'Awaiting order acceptance' );
		$order->save();
		// Recover if PHP stops immediately after WooCommerce records an eligible status.
		self::schedule( $order->get_id(), 1, 90 );
	}

	private static function schedule( $id, $attempt, $delay ) {
		as_schedule_single_action( time() + $delay, self::ACTION, array( (int) $id, (int) $attempt ), self::GROUP, true );
	}

	private static function outbox_name( $id ) {
		return 'inkos_woo_submission_' . (int) $id;
	}

	// WooCommerce saves the order after this hook. Leave a nonpersonal marker so an in-flight
	// gateway callback cannot insert its old contact payload back into an empty outbox.
	public static function erase_contact( $order ) {
		$name = self::outbox_name( $order->get_id() );
		if ( ! $order->get_meta( '_inkos_draft' ) && false === get_option( $name ) ) {
			return;
		}
		global $wpdb;
		$erased = $wpdb->replace( $wpdb->options, array( 'option_name' => $name, 'option_value' => '{"erased":true}', 'autoload' => 'no' ) );
		if ( false === $erased ) {
			throw new \RuntimeException( 'WooCommerce could not erase the InkOS submission. Retry order anonymization.' );
		}
		wp_cache_delete( $name, 'options' );
		$order->delete_meta_data( '_inkos_draft' );
		$order->delete_meta_data( '_inkos_error' );
		$order->delete_meta_data( '_inkos_retry_at' );
		if ( ! $order->get_meta( '_inkos_receipt' ) ) {
			$order->update_meta_data( '_inkos_state', 'Stopped after order anonymization' );
		}
	}

	// Concurrent gateway callbacks must agree on one immutable body, including a possibly late transaction ID.
	// Only the plugin's own non-autoloaded option uses SQL. WooCommerce owns all order storage.
	private static function submission( $order, $draft ) {
		global $wpdb;
		$name = self::outbox_name( $order->get_id() );
		$reference = (string) $order->get_transaction_id();
		if ( '' !== $reference ) {
			$draft['body']['paymentReference'] = $reference;
		}
		$encoded = wp_json_encode( $draft );
		if ( false === $encoded ) {
			throw new ApiError( 'encoding_failed', 'The order contact or reference could not be encoded.', 400 );
		}
		$stored = $wpdb->query( $wpdb->prepare( "INSERT IGNORE INTO {$wpdb->options} (option_name,option_value,autoload) VALUES (%s,%s,'no')", $name, $encoded ) );
		if ( false === $stored ) {
			throw new ApiError( 'outbox_unavailable', 'WooCommerce could not persist the InkOS submission.' );
		}
		$draft = json_decode( (string) $wpdb->get_var( $wpdb->prepare( "SELECT option_value FROM {$wpdb->options} WHERE option_name=%s", $name ) ), true );
		if ( ! empty( $draft['erased'] ) ) {
			throw new ApiError( 'customer_erased', 'This order was anonymized.', 409 );
		}
		if ( empty( $draft['body']['externalOrderId'] ) ) {
			throw new ApiError( 'outbox_unavailable', 'WooCommerce could not recover the original InkOS submission.' );
		}
		return $draft;
	}

	public static function send( $id, $attempt = 0, $manual = false ) {
		$order = wc_get_order( $id );
		if ( ! $order || $order->get_meta( '_inkos_receipt' ) || 'yes' === $order->get_meta( '_anonymized' ) ) {
			return;
		}
		$draft = $order->get_meta( '_inkos_draft' );
		if ( ! $draft || ! $order->has_status( array( 'processing', 'completed', 'on-hold' ) ) || ( ! $manual && 'Needs review' === $order->get_meta( '_inkos_state' ) ) ) {
			return;
		}
		$retry_at = (int) $order->get_meta( '_inkos_retry_at' );
		if ( ! $manual && time() < $retry_at ) {
			self::schedule( $id, $attempt + 1, $retry_at - time() );
			return;
		}
		$delay = min( DAY_IN_SECONDS, 60 * ( 2 ** min( 11, $attempt ) ) );
		// This watchdog is durable before the network call, including a crash after the remote commit.
		self::schedule( $id, $attempt + 1, $delay );
		try {
			$draft = self::submission( $order, $draft );
			$connection = Api::request( 'GET', '/connection' );
			if ( $draft['storefront'] !== ( $connection['storefrontId'] ?? '' ) ) {
				throw new ApiError( 'storefront_changed', 'Reconnect the original storefront before retrying this order.', 409 );
			}
			$body = $draft['body'];
			$result = Api::request( 'POST', '/orders', $body, $body['externalOrderId'] );
			if ( ( $result['externalOrderId'] ?? null ) !== $body['externalOrderId'] || ( $result['totalMinor'] ?? null ) !== $draft['totalMinor']
				|| ( $result['currency'] ?? null ) !== $draft['currency'] || ! is_array( $result['items'] ?? null )
				|| array_column( $result['items'], 'quoteId' ) !== array_column( $body['items'], 'quoteId' ) ) {
				throw new ApiError( 'invalid_receipt', 'InkOS returned different order references or totals. Check the order register.', 409 );
			}
			foreach ( $result['items'] as $line ) {
				if ( empty( $line['orderId'] ) || empty( $line['workOrderId'] ) || empty( $line['orderNumber'] ) || empty( $line['workOrderNumber'] ) ) {
					throw new ApiError( 'invalid_receipt', 'InkOS returned incomplete order references.', 502 );
				}
			}
			$order->update_meta_data( '_inkos_receipt', $result );
			$order->update_meta_data( '_inkos_state', 'Synchronized' );
			$order->delete_meta_data( '_inkos_error' );
			$order->delete_meta_data( '_inkos_retry_at' );
			$order->save();
			self::cancel_watchdogs( $id, $attempt );
		} catch ( ApiError $error ) {
			$order = wc_get_order( $id );
			if ( $order->get_meta( '_inkos_receipt' ) || 'yes' === $order->get_meta( '_anonymized' ) || 'customer_erased' === $error->reason ) {
				return;
			}
			$order->update_meta_data( '_inkos_state', $error->retryable() ? 'Retry scheduled' : 'Needs review' );
			$order->update_meta_data( '_inkos_retry_at', $error->retry_at );
			$order->update_meta_data( '_inkos_error', $error->reason . ' · ' . $error->getMessage() );
			$order->save();
			if ( ! $error->retryable() ) {
				self::cancel_watchdogs( $id, $attempt );
			}
		}
	}

	private static function cancel_watchdogs( $id, $attempt ) {
		foreach ( array_unique( array( 1, $attempt + 1 ) ) as $scheduled_attempt ) {
			as_unschedule_all_actions( self::ACTION, array( (int) $id, (int) $scheduled_attempt ), self::GROUP );
		}
	}

	public static function panel( $order ) {
		$draft = $order->get_meta( '_inkos_draft' );
		$receipt = $order->get_meta( '_inkos_receipt' );
		$state = $order->get_meta( '_inkos_state' );
		if ( ! $draft && ! $receipt && ! $state ) {
			return;
		}
		echo '<h3>InkOS synchronization</h3><p>' . esc_html( $receipt ? 'Synchronized' : $state );
		$external = $receipt['externalOrderId'] ?? $draft['body']['externalOrderId'] ?? '';
		if ( '' !== $external ) {
			echo '<br><code>' . esc_html( $external ) . '</code>';
		}
		echo '</p>';
		if ( $receipt ) {
			foreach ( $receipt['items'] as $line ) {
				echo '<p>Order ' . esc_html( $line['orderNumber'] ) . ' · Work order ' . esc_html( $line['workOrderNumber'] ) . '</p>';
			}
		} else {
			echo '<p>' . esc_html( $order->get_meta( '_inkos_error' ) ) . '</p>';
		}
	}
}
